"""Build reaper_gplink-x64.dll.

1. embeds the GP-Link Lua engine (../scripts) into src/gplink_embedded.h
2. compiles with zig's clang (pip install ziglang) for x86_64-windows-gnu

Usage:  python build.py            (needs: pip install ziglang)
REAPER SDK headers are expected in ./sdk (reaper_plugin.h, reaper_plugin_functions.h).
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LUA_DIR = os.path.join(HERE, "..", "scripts")
EMBED = [  # (file, user_editable)
    ("gplink_core.lua", False),
    ("gplink_formats.lua", False),
    ("gplink_reaper.lua", False),
    ("gplink_config.lua", True),
    ("gplink_autosync_once.lua", False),
    ("GP-Link - Import Guitar Pro file.lua", False),
    ("GP-Link - Sync now.lua", False),
    ("GP-Link - Import structure only.lua", False),
    ("GP-Link - Unlink.lua", False),
    ("README.md", False),
]


def gen_header():
    out = ["// generated by build.py - do not edit", "#pragma once",
           "struct gplink_file { const char *name; const char *data; unsigned len; bool user_editable; };"]
    entries = []
    for i, (name, editable) in enumerate(EMBED):
        data = open(os.path.join(LUA_DIR, name), "rb").read()
        rows = []
        for k in range(0, len(data), 32):
            rows.append(",".join(str(b) for b in data[k:k + 32]))
        out.append(f"static const unsigned char gplink_f{i}[] = {{\n" + ",\n".join(rows) + ",0};")
        entries.append(f'  {{ "{name}", (const char *)gplink_f{i}, {len(data)}u, {"true" if editable else "false"} }},')
    out.append("static const gplink_file GPLINK_EMBEDDED[] = {")
    out += entries
    out.append("};")
    out.append(f"#define GPLINK_EMBEDDED_COUNT {len(EMBED)}")
    path = os.path.join(HERE, "src", "gplink_embedded.h")
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("embedded", len(EMBED), "files ->", path)


def build():
    os.makedirs(os.path.join(HERE, "dist"), exist_ok=True)
    cmd = [sys.executable, "-m", "ziglang", "c++",
           "-target", "x86_64-windows-gnu", "-shared", "-O2", "-std=c++17",
           "-fno-exceptions", "-fno-rtti", "-Wno-unused-parameter",
           "-I", os.path.join(HERE, "sdk"), "-I", os.path.join(HERE, "src"),
           os.path.join(HERE, "src", "gplink_ext.cpp"),
           os.path.join(HERE, "src", "gplink_dialog.cpp"),
           "-o", os.path.join(HERE, "dist", "reaper_gplink-x64.dll"),
           "-luser32", "-lkernel32", "-lgdi32"]
    print(" ".join(cmd))
    subprocess.check_call(cmd)


if __name__ == "__main__":
    gen_header()
    build()
